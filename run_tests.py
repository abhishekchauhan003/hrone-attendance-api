check("overnight date", r.status_code == 201 and r.json()["date"] == "2026-07-06", r.text)
t4 = ms(2026, 7, 7, 18, 30, 0)
r = c.post("/attendance/punch-out", json={"emp_code": "EMP0001", "punched_at": t4})
check("punchout ok", r.status_code == 200 and r.json()["work_hours"] is not None, r.text)
