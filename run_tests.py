"""Contract tests (mongomock, no real Mongo needed)."""
import os, sys
sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import datetime as dt
import mongomock
import app.main as M
M.db = mongomock.MongoClient().db
M.ensure_indexes()
from fastapi.testclient import TestClient
c = TestClient(M.app, raise_server_exceptions=False)
passed = failed = 0
def check(name, cond, extra=""):
    global passed, failed
    if cond:
        passed += 1; print(f"PASS {name}")
    else:
        failed += 1; print(f"FAIL {name} {extra}")
def ms(y, mo, d, h, mi, s=0):
    ist = dt.timezone(dt.timedelta(hours=5, minutes=30))
    return int(dt.datetime(y, mo, d, h, mi, s, tzinfo=ist).timestamp() * 1000)
r = c.post("/employees", json={"emp_code": "EMP0001", "name": "A", "email": "a@x.com", "department": "Eng", "shift_start": "09:30", "shift_end": "18:30", "joined_on": "2026-07-01"})
check("emp create 201", r.status_code == 201, r.text)
check("emp created_at ms", isinstance(r.json().get("created_at"), int))
r = c.post("/employees", json={"emp_code": "EMP0001", "name": "B", "email": "b@x.com", "department": "Eng", "shift_start": "09:30", "shift_end": "18:30", "joined_on": "2026-07-01"})
check("emp dup 409", r.status_code == 409, r.text)
r = c.post("/employees", json={"emp_code": "BAD", "name": "B", "email": "b@x.com", "department": "Eng", "shift_start": "09:30", "shift_end": "18:30", "joined_on": "2026-07-01"})
check("emp bad code 422", r.status_code == 422, r.text)
r = c.post("/employees", json={"emp_code": "EMP0002", "name": "B", "email": "b@x.com", "department": "Eng", "shift_start": "09:30", "shift_end": "09:30", "joined_on": "2026-07-01"})
check("emp equal shifts 422", r.status_code == 422, r.text)
r = c.get("/employees")
check("emp list", r.status_code == 200 and r.json()["total"] >= 1, r.text)
r = c.get("/employees", params={"page_size": 101})
check("emp over page 422", r.status_code == 422, r.text)
c.post("/employees", json={"emp_code": "EMP9001", "name": "N", "email": "n@x.com", "department": "Ops", "shift_start": "22:00", "shift_end": "06:00", "joined_on": "2026-07-01"})
t1 = ms(2026, 7, 7, 9, 40, 0)
r = c.post("/attendance/punch-in", json={"emp_code": "EMP0001", "punched_at": t1})
check("punchin grace 0", r.status_code == 201 and r.json()["late_minutes"] == 0, r.text)
r = c.post("/attendance/punch-in", json={"emp_code": "EMP0001", "punched_at": t1})
check("punchin dup 409", r.status_code == 409, r.text)
r = c.post("/attendance/punch-in", json={"emp_code": "NOPE", "punched_at": t1})
check("punchin unknown 404", r.status_code == 404, r.text)
r = c.post("/attendance/punch-in", json={"emp_code": "EMP0001", "punched_at": 12345})
check("punchin bad ms 422", r.status_code == 422, r.text)
r = c.post("/attendance/punch-in", json={"emp_code": "EMP0001", "punched_at": t1, "status": "ABSENT"})
check("punchin bad status 422", r.status_code == 422, r.text)
t2 = ms(2026, 7, 7, 9, 40, 1)
